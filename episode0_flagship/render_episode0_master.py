def draw_captions(d: ImageDraw.ImageDraw, seg: dict, rel_vt: float) -> None:
    if rel_vt < -0.05:
        return
    ph = next((p for p in seg["phrases"] if p["start"] - 0.08 <= rel_vt <= p["end"]), None)
    if ph is None:
        return

    words = ph["words"]
    sp_w = d.textlength(" ", font=F_SUB)
    wws = [d.textlength(w["text"], font=F_SUB) for w in words]
    tw = sum(wws) + sp_w * max(0, len(words) - 1)

    bx0, bx1 = int(W * 0.5 - tw * 0.5 - 24), int(W * 0.5 + tw * 0.5 + 24)
    d.rounded_rectangle([bx0, H - 88, bx1, H - 26], radius=14, fill=(5, 9, 20, 224), outline=(56, 189, 248, 115), width=1)

    cx_t = W * 0.5 - tw * 0.5
    for w_obj, ww in zip(words, wws):
        active = (w_obj["start"] - 0.04) <= rel_vt <= (w_obj["end"] + 0.09)
        col = (251, 191, 36, 255) if active else ((248, 250, 252, 255) if rel_vt > w_obj["end"] else (186, 198, 216, 232))
        d.text((cx_t, H - 75), w_obj["text"], font=F_SUB, fill=col)
        cx_t += ww + sp_w


def main() -> None:
    # Keep CPU priority BELOW_NORMAL and x264 capped at 2 threads so active games/shader compiles never stutter!
    try:
        import ctypes
        ctypes.windll.kernel32.SetPriorityClass(ctypes.windll.kernel32.GetCurrentProcess(), 0x00004000)
    except Exception:
        pass

    t0 = time.perf_counter()
    manifest = json.loads(MANIFEST_PATH.read_text(encoding="utf-8"))
    wav_path, segments, total_dur = build_soundtrack_and_timeline(manifest)
    total_frames = int(math.ceil(total_dur * FPS))

    print(f"Rendering Flagship Episode 0: {total_frames} frames ({total_dur/60.0:.2f} min @ {FPS}fps) [Low-Priority Game-Safe Mode]...", flush=True)
    ffmpeg_exe = imageio_ffmpeg.get_ffmpeg_exe()
    log_f = open(AUDIO_DIR / "ep0_ffmpeg.log", "wb")
    cmd = [
        ffmpeg_exe, "-y", "-loglevel", "error",
        "-f", "rawvideo", "-vcodec", "rawvideo", "-s", f"{W}x{H}", "-pix_fmt", "rgb24", "-r", str(FPS),
        "-i", "-", "-i", str(wav_path),
        "-c:v", "libx264", "-threads", "2", "-preset", "veryfast", "-crf", "21", "-pix_fmt", "yuv420p",
        "-c:a", "aac", "-b:a", "192k", "-shortest", "-movflags", "+faststart",
        str(OUT_MP4),
    ]
    creationflags = getattr(subprocess, "BELOW_NORMAL_PRIORITY_CLASS", 0)
    proc = subprocess.Popen(cmd, stdin=subprocess.PIPE, stdout=subprocess.DEVNULL, stderr=log_f, creationflags=creationflags)
    assert proc.stdin is not None

    loaded_idx: Optional[int] = None
    active_clip: Optional[SceneCinemaClip] = None

    def get_clip_for_idx(idx: int) -> SceneCinemaClip:
        nonlocal loaded_idx, active_clip
        if loaded_idx != idx or active_clip is None:
            active_clip = None
            gc.collect()
            c_name = segments[idx]["cinema_clip"]
            fb_name = FALLBACK_BY_ID.get(segments[idx]["id"], "act1_weave.png")
            active_clip = SceneCinemaClip(CINEMA_DIR / c_name, FALLBACK_ASSETS / fb_name)
            loaded_idx = idx
        return active_clip

    for f_i in range(total_frames):
        t_sec = f_i / float(FPS)
        seg = next((s for s in segments if s["seg_start"] <= t_sec < s["seg_end"]), None)

        if seg is not None:
            idx = seg["index"]
            clip = get_clip_for_idx(idx)
            prog = (t_sec - seg["seg_start"]) / max(0.01, seg["seg_end"] - seg["seg_start"])

            # Smooth blend schedule:
            # 0.00 -> 0.30: Full-bleed AI Cinema Video (model_alpha = 0)
            # 0.30 -> 0.37: Cross-dissolve into Coded Python 3D Simulation (model_alpha 0 -> 1)
            # 0.37 -> 0.87: Coded Python 3D Simulation up front + dimmed AI Cinema motion behind
            # 0.87 -> 0.94: Dissolve back to full-bleed AI Cinema Video for closing breath
            if prog < 0.30:
                model_alpha = 0.0
            elif prog < 0.37:
                model_alpha = (prog - 0.30) / 0.07
            elif prog < 0.87:
                model_alpha = 1.0
            elif prog < 0.94:
                model_alpha = 1.0 - (prog - 0.87) / 0.07
            else:
                model_alpha = 0.0

            base = clip.get_frame(t_sec - seg["seg_start"], dim_factor=1.0 - model_alpha).convert("RGBA")
            ov = Image.new("RGBA", (W, H), (0, 0, 0, 0))
            d = ImageDraw.Draw(ov)

            # Sleek Top Documentary Header
            d.rectangle([0, 0, W, 62], fill=(5, 10, 22, 205))
            d.line([(0, 62), (W, 62)], fill=(56, 189, 248, 115), width=2)
            d.rectangle([0, 0, int(W * (t_sec / total_dur)), 4], fill=(56, 189, 248, 255))

            ch_w = int(d.textlength(seg["chapter"], font=F_PART)) + 24
            d.rounded_rectangle([20, 15, 20 + ch_w, 48], radius=8, fill=(56, 189, 248, 42), outline=(56, 189, 248, 220), width=1)
            d.text((32, 21), seg["chapter"], font=F_PART, fill=(56, 189, 248, 255))
            d.text((34 + ch_w, 17), seg["title"], font=F_TITLE, fill=(248, 250, 252, 255))

            # Subtle mode pill below header when Python 3D Simulation is active
            if model_alpha > 0.15:
                tag = seg["subtitle_tag"]
                bw = int(d.textlength(tag, font=F_TAG)) + 26
                d.rounded_rectangle([20, 72, 20 + bw, 100], radius=7, fill=(6, 18, 28, int(210 * model_alpha)), outline=(52, 211, 153, int(210 * model_alpha)), width=1)
                d.text((33, 77), tag, font=F_TAG, fill=(52, 211, 153, int(255 * model_alpha)))

            draw_python_3d_model(d, seg["id"], prog, t_sec, model_alpha)
            draw_captions(d, seg, t_sec - seg["voice_start"])
            rgb = Image.alpha_composite(base, ov).convert("RGB")

            if f_i in (220, 950, 4800, 9600):
                rgb.save(EP0_DIR / f"preview_ep0_frame_{f_i}.png")

        elif t_sec < segments[0]["seg_start"]:
            clip = get_clip_for_idx(0)
            base = clip.get_frame(t_sec, dim_factor=0.55).convert("RGBA")
            ov = Image.new("RGBA", (W, H), (4, 8, 20, 120))
