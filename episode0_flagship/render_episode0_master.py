class SceneCinemaClip:
    """Loads one 10s 1280x720 Gemini Omni video clip into uint8 frames for seamless ping-pong motion."""

    def __init__(self, clip_path: Path, fallback_png: Path) -> None:
        self.frames: List[np.ndarray] = []
        ffmpeg_exe = imageio_ffmpeg.get_ffmpeg_exe()
        if clip_path.exists() and clip_path.stat().st_size > 10000:
            cmd = [
                ffmpeg_exe, "-loglevel", "error", "-i", str(clip_path),
                "-vf", f"scale={W}:{H}:force_original_aspect_ratio=increase,crop={W}:{H}",
                "-r", str(FPS), "-f", "rawvideo", "-pix_fmt", "rgb24", "-",
            ]
            raw = subprocess.run(cmd, capture_output=True).stdout
            frame_bytes = W * H * 3
            n_f = len(raw) // frame_bytes
            for i in range(n_f):
                arr = np.frombuffer(raw[i * frame_bytes : (i + 1) * frame_bytes], dtype=np.uint8).reshape((H, W, 3))
                self.frames.append(arr)
            print(f"    [AI Cinema Loaded] {clip_path.name} ({len(self.frames)} HD frames)", flush=True)

        if not self.frames:
            # High-res Ken-Burns fallback if clip missing
            src = Image.open(fallback_png).convert("RGB").resize((1440, 810), Image.Resampling.LANCZOS)
            for i in range(180):
                p = i / 179.0
                ox = int(80 + 65 * math.sin(p * math.pi - 0.5))
                oy = int(45 + 35 * math.cos(p * math.pi))
                self.frames.append(np.asarray(src.crop((ox, oy, ox + W, oy + H)), dtype=np.uint8))
            print(f"    [Fallback Artwork] {fallback_png.name}")

        # Pre-compute dimmed/softened frames once per 240-frame clip (5x faster & ultra-low CPU!)
        self.dim_frames: List[np.ndarray] = []
        for arr in self.frames:
            im_d = ImageEnhance.Brightness(Image.fromarray(arr, mode="RGB")).enhance(0.38)
            im_d = im_d.filter(ImageFilter.GaussianBlur(radius=1.4))
            self.dim_frames.append(np.asarray(im_d, dtype=np.uint8))

    def get_frame(self, local_t: float, dim_factor: float) -> Image.Image:
        """Returns smooth ping-pong frame at 0.80x speed; dims cleanly when Python 3D model is active."""
        n = len(self.frames)
        if n == 1:
            full_arr = self.frames[0]
            dim_arr = self.dim_frames[0]
        else:
            pos = local_t * FPS * 0.80
            cycle = 2 * (n - 1)
            m = pos % cycle
            f_pos = m if m <= (n - 1) else (cycle - m)
            i0 = int(math.floor(f_pos))
            i1 = min(n - 1, i0 + 1)
            alpha = f_pos - i0
            if alpha < 0.02 or i0 == i1:
                full_arr = self.frames[i0]
                dim_arr = self.dim_frames[i0]
            else:
                w0, w1 = 1.0 - alpha, alpha
                full_arr = (w0 * self.frames[i0].astype(np.float32) + w1 * self.frames[i1].astype(np.float32)).astype(np.uint8)
                dim_arr = (w0 * self.dim_frames[i0].astype(np.float32) + w1 * self.dim_frames[i1].astype(np.float32)).astype(np.uint8)

        if dim_factor >= 0.98:
            return Image.fromarray(full_arr, mode="RGB")
        if dim_factor <= 0.02:
            return Image.fromarray(dim_arr, mode="RGB")
        arr = (dim_factor * full_arr.astype(np.float32) + (1.0 - dim_factor) * dim_arr.astype(np.float32)).astype(np.uint8)
        return Image.fromarray(arr, mode="RGB")


