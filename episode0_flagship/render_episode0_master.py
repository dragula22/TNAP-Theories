def proj3d(x: float, y: float, z: float, cx: float, cy: float, yaw: float, pitch: float, fov: float = 360.0):
    cyw, syw = math.cos(yaw), math.sin(yaw)
    cp, sp = math.cos(pitch), math.sin(pitch)
    x1, z1 = x * cyw - z * syw, x * syw + z * cyw
    y2, z2 = y * cp - z1 * sp, y * sp + z1 * cp + 5.0
    sc = fov / max(0.9, z2)
    return cx + x1 * sc, cy - y2 * sc


