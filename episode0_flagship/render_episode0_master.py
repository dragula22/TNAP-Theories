    proc.stdin.close()
    ret = proc.wait()
    log_f.close()
    if ret != 0:
        err = (AUDIO_DIR / "ep0_ffmpeg.log").read_text(encoding="utf-8", errors="replace")[-600:]
        raise RuntimeError(f"FFmpeg failed ({ret}): {err}")

    shutil.copy2(OUT_MP4, ARTIFACT_MP4)
    print(f"[COMPLETE] Flagship Episode 0 rendered: {OUT_MP4} ({OUT_MP4.stat().st_size/1e6:.1f} MB) in {time.perf_counter()-t0:.1f}s!")


