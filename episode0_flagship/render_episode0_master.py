def build_soundtrack_and_timeline(manifest: dict) -> Tuple[Path, List[dict], float]:
    ffmpeg_exe = imageio_ffmpeg.get_ffmpeg_exe()
    intro_sec = 2.8
    gap_sec = 1.25
    outro_sec = 3.2

    def sil(sec: float) -> np.ndarray:
        return np.zeros((int(round(sec * SR)), 2), dtype=np.float32)

    probe_draw = ImageDraw.Draw(Image.new("RGBA", (16, 16)))
    sp_w = probe_draw.textlength(" ", font=F_SUB)

    voice_parts: List[np.ndarray] = [sil(intro_sec)]
    cursor = intro_sec
    segments = []

    for idx, sc in enumerate(manifest["scenes"]):
        tmp_44k = AUDIO_DIR / f"_tmp_{sc['id']}_44k.wav"
        subprocess.run(
            [ffmpeg_exe, "-y", "-loglevel", "error", "-i", sc["wav_path"], "-ar", str(SR), "-ac", "2", str(tmp_44k)],
            check=True,
        )
        with wave.open(str(tmp_44k), "rb") as wf:
            pcm = np.frombuffer(wf.readframes(wf.getnframes()), dtype=np.int16).astype(np.float32).reshape(-1, 2) / 32768.0
        tmp_44k.unlink(missing_ok=True)

        pre_pad = 0.40
        post_pad = gap_sec - pre_pad
        voice_parts.extend([sil(pre_pad), pcm, sil(post_pad)])

        act_dur = len(pcm) / float(SR)
        seg_start = cursor
        voice_start = cursor + pre_pad
        seg_end = cursor + pre_pad + act_dur + post_pad
        cursor = seg_end

        # Group words into clean width-safe subtitle lines
        phrases, cur_grp, cur_w = [], [], 0.0
        for w_obj in sc["words"]:
            ww = probe_draw.textlength(w_obj["text"], font=F_SUB)
            add_w = ww if not cur_grp else (sp_w + ww)
            if cur_grp and (cur_w + add_w > 1050.0 or len(cur_grp) >= 8):
                phrases.append({"start": cur_grp[0]["start"], "end": cur_grp[-1]["end"] + 0.22, "words": cur_grp})
                cur_grp, cur_w = [w_obj], ww
            else:
                cur_grp.append(w_obj)
                cur_w += add_w
        if cur_grp:
            phrases.append({"start": cur_grp[0]["start"], "end": cur_grp[-1]["end"] + 0.24, "words": cur_grp})

        segments.append(
            {
                "index": idx,
                "id": sc["id"],
                "chapter": sc["chapter"],
                "title": sc["title"],
                "subtitle_tag": sc["subtitle_tag"],
                "cinema_clip": sc["cinema_clip"],
                "seg_start": seg_start,
                "voice_start": voice_start,
                "seg_end": seg_end,
                "phrases": phrases,
            }
        )

    voice_parts.append(sil(outro_sec))
    total_dur = cursor + outro_sec
    full_voice = np.vstack(voice_parts)
    n_total = len(full_voice)

    # Warm, subtle ambient space-pad chord progression (turned way down under speech per user feedback!)
    t = np.arange(n_total, dtype=np.float32) / float(SR)
    chords = [
        [146.83, 220.00, 261.63, 329.63],
        [116.54, 174.61, 220.00, 293.66],
        [130.81, 174.61, 220.00, 261.63],
        [130.81, 196.00, 261.63, 293.66],
    ]
    chord_period = 16.0
    pad_l = np.zeros(n_total, dtype=np.float32)
    pad_r = np.zeros(n_total, dtype=np.float32)

    for c_i, freqs in enumerate(chords):
        ph = ((t / chord_period) - c_i) % len(chords)
        wt = np.where(ph < 1.0, 0.5 * (1.0 - np.cos(2.0 * np.pi * ph)), 0.0)
        ph2 = ((t / chord_period) - c_i + 0.5) % len(chords)
        wt = np.maximum(wt, np.where(ph2 < 1.0, 0.35 * (1.0 - np.cos(2.0 * np.pi * ph2)), 0.0))
        for f_i, f_hz in enumerate(freqs):
            det = 1.0 + 0.0016 * (f_i - 1.5)
            lfo = 0.88 + 0.12 * np.sin(2.0 * np.pi * (0.06 + 0.02 * f_i) * t + f_i)
            pad_l += wt * lfo * np.sin(2.0 * np.pi * f_hz * t) * (0.25 / len(freqs))
            pad_r += wt * lfo * np.sin(2.0 * np.pi * (f_hz * det) * t + 0.45) * (0.25 / len(freqs))

    # Ultra-gentle ducking: ~0.024 gain (-32 dB) during speech, ~0.055 (-25 dB) during silent gaps/titles
    v_env = np.abs(full_voice[:, 0]) + np.abs(full_voice[:, 1])
    win = int(0.30 * SR)
    kern = np.ones(win, dtype=np.float32) / float(win)
    sm_env = np.convolve(v_env, kern, mode="same")
    m_gain = np.where(sm_env > 0.012, 0.024, 0.058).astype(np.float32)
    m_gain = np.convolve(m_gain, kern, mode="same")

    fade = np.clip(np.minimum(t / 1.4, (total_dur - t) / 2.4), 0.0, 1.0)
    mix_l = np.clip(full_voice[:, 0] * 0.96 + pad_l * m_gain * fade, -0.99, 0.99)
    mix_r = np.clip(full_voice[:, 1] * 0.96 + pad_r * m_gain * fade, -0.99, 0.99)
    pcm16 = (np.column_stack([mix_l, mix_r]) * 32767.0).astype(np.int16)

    with wave.open(str(MASTER_WAV), "wb") as wf_out:
        wf_out.setnchannels(2)
        wf_out.setsampwidth(2)
        wf_out.setframerate(SR)
        wf_out.writeframes(pcm16.tobytes())

    return MASTER_WAV, segments, total_dur


