            t1 = "THE UNIVERSE INSIDE OUT"
            t2 = "A Visual Guide to the Stretched Fabric & Upside-Down Cosmic Hourglass"
            w1, w2 = d.textlength(t1, font=F_HERO), d.textlength(t2, font=F_HERO_SUB)
            d.text(((W - w1) * 0.5, H * 0.40), t1, font=F_HERO, fill=(248, 250, 252, 255))
